const normalizeLanguageText = (value) => value.replace(/\s+/g, " ").trim();
const reverseHomepageTranslations = Object.fromEntries(
  Object.entries(homepageTranslations).map(([bulgarian, english]) => [normalizeLanguageText(english), bulgarian]),
);
const languageSelect = document.querySelector("[data-language-select]");
const originalText = new WeakMap();
const originalAttributes = new WeakMap();
let currentLanguage = "bg";
let applyingLanguage = false;
let languageObserver;

const observeLanguageChanges = () => {
  languageObserver?.observe(document.body, { subtree: true, characterData: true, childList: true });
};

const translateValue = (value, language) => {
  const normalized = normalizeLanguageText(value);
  return language === "en"
    ? homepageTranslations[normalized] ?? value
    : reverseHomepageTranslations[normalized] ?? value;
};

const applyTextNodeLanguage = (node, language, capture = false) => {
  if (capture || !originalText.has(node)) originalText.set(node, node.nodeValue ?? "");
  const current = node.nodeValue ?? "";
  const source = language === "bg" ? current : originalText.get(node) ?? current;
  const translated = translateValue(source, language);
  if (translated === source) return;
  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  node.nodeValue = `${leading}${translated}${trailing}`;
  if (language === "bg") originalText.set(node, node.nodeValue);
};

const applyAttributeLanguage = (element, language) => {
  const names = ["aria-label", "placeholder", "title"];
  if (!originalAttributes.has(element)) {
    originalAttributes.set(element, Object.fromEntries(names.map((name) => [name, element.getAttribute(name)])));
  }
  const attributes = originalAttributes.get(element);
  names.forEach((name) => {
    const source = attributes[name];
    if (source == null) return;
    element.setAttribute(name, translateValue(source, language));
  });
};

const allTextNodes = () => {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode: (node) => /\S/.test(node.nodeValue ?? "") && !["SCRIPT", "STYLE"].includes(node.parentElement?.tagName)
      ? NodeFilter.FILTER_ACCEPT
      : NodeFilter.FILTER_REJECT,
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  return nodes;
};

const applyLanguage = (language) => {
  languageObserver?.disconnect();
  currentLanguage = language === "en" ? "en" : "bg";
  applyingLanguage = true;
  allTextNodes().forEach((node) => applyTextNodeLanguage(node, currentLanguage));
  document.querySelectorAll("[aria-label], [placeholder], [title]").forEach((element) => applyAttributeLanguage(element, currentLanguage));
  document.documentElement.lang = currentLanguage;
  document.body.dataset.language = currentLanguage;
  document.title = translateValue("Софтуер за управление на транспортна фирма | LogiTruck", currentLanguage);
  if (languageSelect) languageSelect.value = currentLanguage;
  applyingLanguage = false;
  observeLanguageChanges();
  window.dispatchEvent(new CustomEvent("logitruck:languagechange", { detail: { language: currentLanguage } }));
};

languageObserver = new MutationObserver((mutations) => {
  if (applyingLanguage) return;
  applyingLanguage = true;
  languageObserver.disconnect();
  mutations.forEach((mutation) => {
    if (mutation.type === "characterData") {
      const node = mutation.target;
      const normalized = normalizeLanguageText(node.nodeValue ?? "");
      if (currentLanguage === "bg" || homepageTranslations[normalized]) {
        originalText.set(node, node.nodeValue ?? "");
        applyTextNodeLanguage(node, currentLanguage);
      }
      return;
    }

    mutation.addedNodes.forEach((addedNode) => {
      const nodes = addedNode.nodeType === Node.TEXT_NODE
        ? [addedNode]
        : [...addedNode.childNodes].flatMap((child) => child.nodeType === Node.TEXT_NODE ? [child] : []);
      nodes.forEach((node) => {
        if (!/\S/.test(node.nodeValue ?? "")) return;
        originalText.set(node, node.nodeValue ?? "");
        applyTextNodeLanguage(node, currentLanguage);
      });
    });
  });
  applyingLanguage = false;
  observeLanguageChanges();
});

observeLanguageChanges();

let savedLanguage = "bg";
try {
  savedLanguage = localStorage.getItem("logitruck-language") ?? "bg";
} catch {
  savedLanguage = "bg";
}

languageSelect?.addEventListener("change", (event) => {
  const language = event.currentTarget.value;
  try { localStorage.setItem("logitruck-language", language); } catch { /* Language preference remains session-only. */ }
  applyLanguage(language);
});

applyLanguage(savedLanguage);
